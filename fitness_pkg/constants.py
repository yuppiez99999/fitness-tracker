# 按目标肌群关键词推断 emoji
def _emoji_for_target(target: str) -> str:
    """根据目标肌群中英文返回emoji"""
    if not target:
        return MUSCLE_EMOJI['默认']
    t = target
    # 按优先级匹配
    for key, emoji in MUSCLE_EMOJI.items():
        if key in t:
            return emoji
    return MUSCLE_EMOJI['默认']


